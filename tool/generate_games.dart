// Scans lib/games/*/game.dart and writes lib/games/games.g.dart.
// Run after adding or removing a game folder:
//   dart run tool/generate_games.dart
import 'dart:io';

void main() {
  final gamesDir = Directory('lib/games');
  final names = gamesDir
      .listSync()
      .whereType<Directory>()
      .where((dir) => File('${dir.path}/game.dart').existsSync())
      .map((dir) => dir.uri.pathSegments.where((s) => s.isNotEmpty).last)
      .toList()
    ..sort();

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_games.dart — do not edit by hand.')
    ..writeln('// Run `dart run tool/generate_games.dart` after adding a game folder.')
    ..writeln()
    ..writeln("import 'minigame.dart';");
  for (final name in names) {
    out.writeln("import '$name/game.dart' as $name;");
  }
  out
    ..writeln()
    ..writeln('final allGames = <Minigame>[');
  for (final name in names) {
    out.writeln('  $name.minigame,');
  }
  out.writeln('];');

  File('${gamesDir.path}/games.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Generated ${names.length} games: ${names.join(', ')}');
}
